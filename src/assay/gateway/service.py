"""Host-owned admission, frozen inputs, container dispatch, and evidence capture."""

from __future__ import annotations

import hashlib
import re
import tempfile
import threading
import time
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from uuid import uuid4

from safety_lab.config import state_directory
from safety_lab.contracts import DatasetSnapshot, TaskSpec, canonical_json_bytes
from safety_lab.contracts.execution import ExecutionReceipt, WorkerSuccess
from safety_lab.contracts.experiment import ResourceLimits
from safety_lab.datasets import validate_public_bundle
from safety_lab.evidence.store import EvidenceStore
from safety_lab.execution.docker import execute_container, load_worker
from safety_lab.gateway.policy import validate_sql

_RUN_ID = re.compile(r"[a-zA-Z0-9][a-zA-Z0-9_.-]{0,159}")


@dataclass(frozen=True)
class QueryOutcome:
    receipt: ExecutionReceipt
    result: WorkerSuccess | None


def freeze_input_bundle(
    bundle: Path, evidence_root: Path
) -> tuple[Path, DatasetSnapshot, TaskSpec]:
    """Freeze exact allowlisted source bytes before dispatch, never mount a live input."""
    snapshot = validate_public_bundle(bundle)
    manifest_hash = hashlib.sha256(canonical_json_bytes(snapshot)).hexdigest()
    inputs = evidence_root / "inputs"
    inputs.mkdir(parents=True, exist_ok=True)
    destination = inputs / manifest_hash
    if not destination.exists():
        with tempfile.TemporaryDirectory(prefix="snapshot-", dir=inputs) as temporary:
            staging = Path(temporary)
            if not staging.resolve().is_relative_to(inputs.resolve()):
                raise ValueError("Snapshot staging escaped the evidence root")
            if not destination.resolve().is_relative_to(inputs.resolve()):
                raise ValueError("Snapshot destination escaped the evidence root")
            files = ["task.json", "manifest.json", "manifest.sha256"]
            files.extend(table.path for table in snapshot.tables)
            for name in files:
                target = staging / name
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes((bundle / name).read_bytes())
            if validate_public_bundle(staging) != snapshot:
                raise ValueError("Input changed while capturing snapshot")
            # Linux bind mounts keep host modes, and the worker's fixed UID is not the
            # host owner; mkdtemp (and a strict umask) would leave this owner-only.
            for path in (staging, *staging.rglob("*")):
                path.chmod(0o755 if path.is_dir() else 0o644)
            try:
                staging.rename(destination)
            except OSError:
                # Another host writer may have frozen identical content first.
                if not destination.is_dir() or validate_public_bundle(destination) != snapshot:
                    raise
    if validate_public_bundle(destination) != snapshot:
        raise ValueError("Stored input snapshot differs from requested source")
    task = TaskSpec.model_validate_json((destination / "task.json").read_bytes())
    return destination, snapshot, task


def execute_query(
    query: str,
    bundle: Path,
    *,
    state: Path | None = None,
    limits: ResourceLimits | None = None,
    cancel: threading.Event | None = None,
    run_id: str | None = None,
) -> QueryOutcome:
    """Execute only in Docker; receipt and run identities are generated by the host.

    ``run_id`` comes from the trusted episode runner, never from analyst input.
    """
    if run_id is not None and _RUN_ID.fullmatch(run_id) is None:
        raise ValueError("run_id must be a bounded host identifier")
    root = state or state_directory()
    evidence_root = root / "evidence"
    frozen_bundle, snapshot, task = freeze_input_bundle(bundle, evidence_root)
    admitted = validate_sql(query, task.allowed_tables)
    image = load_worker(root)
    started = datetime.now(UTC)
    start_clock = time.monotonic()
    outcome = execute_container(
        image,
        frozen_bundle,
        admitted.normalized_sql,
        task.allowed_tables,
        limits or ResourceLimits(),
        cancel,
    )
    finished = datetime.now(UTC)
    result_hash = (
        hashlib.sha256(canonical_json_bytes(outcome.result)).hexdigest()
        if outcome.result is not None
        else None
    )
    row_count = outcome.result.row_count if outcome.result is not None else None
    preview_count = min(20, row_count) if row_count is not None else None
    receipt = ExecutionReceipt(
        execution_id="execution-" + uuid4().hex,
        run_id=run_id or "run-" + uuid4().hex,
        snapshot_id=snapshot.snapshot_id,
        snapshot_manifest_sha256=hashlib.sha256(canonical_json_bytes(snapshot)).hexdigest(),
        task_id=task.task_id,
        exact_query=admitted.exact_sql,
        query_sha256=admitted.query_sha256,
        normalized_query=admitted.normalized_sql,
        source_ids=admitted.source_ids,
        policy_version=admitted.policy_version,
        worker_image_id=image.image_id,
        started_at=started,
        finished_at=finished,
        elapsed_ms=max(0, int((time.monotonic() - start_clock) * 1000)),
        status=outcome.status,
        error_code=outcome.error_code,
        result_id="result-" + result_hash if result_hash is not None else None,
        output_sha256=result_hash,
        row_count=row_count,
        preview_row_count=preview_count,
        preview_truncated=row_count is not None and row_count > 20,
    )
    EvidenceStore(evidence_root).record_execution(receipt, outcome.result, snapshot, task)
    return QueryOutcome(receipt, outcome.result)
